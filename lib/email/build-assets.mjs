// Regenerates assets.ts from the PNGs in ./assets (run: node lib/email/build-assets.mjs).
// The PNGs are inline email images: the illustration and icons are exported from the Figma file
// "[DS] Foundation Elegix" (Email Template / Welcome eng), the logo from components/ui/Logo.tsx, at 2x.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = join(import.meta.dirname, "assets");
const files = readdirSync(dir).filter((f) => f.endsWith(".png")).sort();
const body = files.map((f) => `  "${f}": "${readFileSync(join(dir, f)).toString("base64")}",`).join("\n");
writeFileSync(join(import.meta.dirname, "assets.ts"), `// Generated by build-assets.mjs. Do not edit by hand.\nexport const EMAIL_ASSETS: Record<string, string> = {\n${body}\n};\n`);
console.log(files.length, "assets");
